#!/usr/bin/env node
/**
 * The API's types come from its contract, never by hand (ADR 0014).
 * medora-backend generates contract/openapi.json; this turns it into
 * src/lib/api/schema.d.ts.
 *
 *   npm run contract            write schema.d.ts
 *   npm run contract -- --check fail when schema.d.ts is not what the contract makes
 *
 * The contract is read from, in order:
 *   1. a checkout of medora-backend beside this repo (../medora-backend);
 *   2. in CI, medora-backend on GitHub, read with SIBLING_REPO_TOKEN: the
 *      branch of the same name if it exists (a pair of pull requests), else main.
 * In CI a missing token fails the run. Elsewhere, with no checkout, it says it skipped.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const OUT = "src/lib/api/schema.d.ts";
const LOCAL = "../medora-backend/contract/openapi.json";
const HEADER = "/**\n * Generated by `npm run contract` from medora-backend's contract/openapi.json (ADR 0014).\n * Never edit by hand: change the API, regenerate its contract, then run the script again.\n */\n\n";

async function contract() {
  if (existsSync(LOCAL)) return { text: readFileSync(LOCAL, "utf8"), from: LOCAL };
  if (!process.env.CI) return null;
  const token = process.env.SIBLING_REPO_TOKEN;
  if (!token) {
    console.error("SIBLING_REPO_TOKEN is not set, so the API contract can't be read from medora-backend. Add a read-only token as a repository secret.");
    process.exit(1);
  }
  const owner = (process.env.GITHUB_REPOSITORY ?? "").split("/")[0];
  const api = `https://api.github.com/repos/${owner}/medora-backend`;
  const headers = { authorization: `Bearer ${token}`, "user-agent": "medora-contract", "x-github-api-version": "2022-11-28" };
  const branch = process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || "main";
  const ref = (await fetch(`${api}/branches/${encodeURIComponent(branch)}`, { headers })).ok ? branch : "main";
  const file = await fetch(`${api}/contents/contract/openapi.json?ref=${encodeURIComponent(ref)}`, { headers: { ...headers, accept: "application/vnd.github.raw" } });
  if (!file.ok) {
    console.error(`Could not read medora-backend's contract at ${ref}: ${file.status}`);
    process.exit(1);
  }
  return { text: await file.text(), from: `medora-backend@${ref}` };
}

const source = await contract();
if (!source) {
  console.log("Contract types: skipped, no ../medora-backend checkout here. CI reads it from GitHub.");
  process.exit(0);
}
const ast = await openapiTS(JSON.parse(source.text), { exportType: true, alphabetize: true });
const generated = HEADER + astToString(ast);

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== generated) {
    console.error(`${OUT} is not what ${source.from} makes. Run npm run contract and commit the result.`);
    process.exit(1);
  }
  console.log(`Contract types: ${OUT} matches ${source.from}.`);
} else {
  writeFileSync(OUT, generated);
  console.log(`Wrote ${OUT} from ${source.from}.`);
}
